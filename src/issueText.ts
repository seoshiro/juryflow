export function issueText(issue: Issue, project: Project, language: 'en' | 'ru'): string {
  if (language === 'en') return issue.message;
  const names = issue.teamIds?.map(id => project.teams.find(team => team.id === id)?.name ?? id);
  return `${russian[issue.code] ?? 'Проверьте ограничения события и повторите поиск.'}${names?.length ? ` Команды: ${names.join(', ')}.` : ''}`;
}
